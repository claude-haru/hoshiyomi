/**
 * アスペクト（天体間の角度）の意味。
 * key は天体2つを規定の順に並べたもの（例 "sun-moon"）。
 * harmony = トライン/セクスタイル、tension = スクエア/オポジション/クインカンクス、
 * conjunction = コンジャンクション（無ければ両者の中間的な説明を合成）。
 */
export interface AspectText {
  harmony: string;
  tension: string;
  conjunction?: string;
}

/** key を作るときの天体の並び順 */
export const BODY_ORDER = [
  'sun', 'moon', 'mercury', 'venus', 'mars', 'jupiter', 'saturn',
  'uranus', 'neptune', 'pluto', 'northNode', 'southNode', 'ascendant', 'mc',
];

export function aspectKey(a: string, b: string): string {
  const ia = BODY_ORDER.indexOf(a);
  const ib = BODY_ORDER.indexOf(b);
  return ia <= ib ? `${a}-${b}` : `${b}-${a}`;
}

